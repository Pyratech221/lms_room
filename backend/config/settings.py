# Sessions longues : le lien magique ne sert qu'a la premiere connexion. La duree repart
# de zero a chaque visite, un usage regulier ne demande donc jamais de se reconnecter.
#
# Le cookie est persistant et survit a la fermeture de l'application installee : une PWA
# rouverte des mois plus tard retrouve sa session. Le delai ne court que depuis la
# derniere visite, pas depuis la connexion. Se deconnecter reste possible a tout moment
# depuis la barre laterale.
